"""Run this checkout's font tests without installing packages or making wheels.

Use matching PyMuPDF 2.x main Python bindings with pytest already installed.
"""
from pathlib import Path
import os
import shutil
import subprocess
import sys
import tempfile

import pymupdf


def main():
    root = Path(__file__).resolve().parents[1]
    version = tuple(map(int, pymupdf.__version__.split('.')))
    if version[0] != 2:
        raise RuntimeError('Use an existing PyMuPDF 2.x environment.')
    if not callable(getattr(pymupdf, '_layout_available', None)):
        raise RuntimeError(
            'Use matching PyMuPDF main Python bindings (1d34e04 or compatible); '
            'older draft-c bindings lack the layout API required by this main.'
        )
    with tempfile.TemporaryDirectory(prefix='ocr-writeback-tests-') as temporary:
        package = Path(temporary) / 'pymupdf4llm'
        shutil.copytree(root / 'src', package,
                        ignore=shutil.ignore_patterns('__pycache__'))
        # This file is normally generated by the PyMuPDF 2.x build.
        (package / 'versions_file.py').write_text(
            f'VERSION = {pymupdf.__version__!r}\n'
            f'VERSION_TUPLE = {version!r}\n'
        )
        environment = dict(os.environ)
        environment['PYTHONDONTWRITEBYTECODE'] = '1'
        environment['PYTHONPATH'] = os.pathsep.join(
            [temporary, environment.get('PYTHONPATH', '')]
        )
        # Import the overlaid package first: older 2.x Python bindings import
        # pymupdf4llm before completing their own layout initialization.
        bootstrap = (
            'import sys; import pymupdf4llm; import pytest; '
            'sys.exit(pytest.main(sys.argv[1:]))'
        )
        result = subprocess.run(
            [sys.executable, '-c', bootstrap, '--noconftest', '-q',
             str(root / 'tests/test_ocr_writeback_fonts.py'),
             '-p', 'no:cacheprovider'],
            env=environment,
            check=False,
        )
        return result.returncode


if __name__ == '__main__':
    raise SystemExit(main())
